#!/usr/bin/env python3
"""Render catalog/SKILL_CATALOG.md and catalog/ROADMAP.md from catalog/skills.yaml.

The YAML is the source of truth; the markdown files are generated views. CI runs this with `--check`
so the two cannot drift.

Usage:
    python3 tools/render_catalog.py [--root DIR] [--check]
"""

from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import lintlib  # noqa: E402
import yamlmini  # noqa: E402

STATUS_ORDER = ("flagship", "prototype", "planned", "deferred", "deprecated")
STATUS_LABEL = {
    "flagship": "Flagship",
    "prototype": "Prototype",
    "planned": "Planned",
    "deferred": "Deferred",
    "deprecated": "Deprecated",
}
FAMILY_LABEL = {
    "core": "Core and meta",
    "engineering": "Software engineering",
    "security": "Security engineering",
    "performance": "Performance engineering",
    "systems": "Systems and reverse engineering",
    "research": "Research and decision support",
    "architecture": "Architecture",
    "ai-ml": "AI and data",
    "documentation": "Documentation and developer experience",
}

HEADER = """<!-- Generated by tools/render_catalog.py from catalog/skills.yaml. Do not edit by hand. -->

# UniSkills Catalog

`catalog/skills.yaml` is the machine-readable source of truth. This page is a generated view; run
`python3 tools/render_catalog.py` after editing the YAML.

**Totals:** {flagship} flagship, {planned} planned, {deferred} deferred, {total} entries.

"""


def render_catalog(entries):
    counts = {status: 0 for status in STATUS_ORDER}
    for entry in entries:
        counts[entry.get("status", "planned")] += 1
    out = [HEADER.format(
        flagship=counts["flagship"],
        planned=counts["planned"],
        deferred=counts["deferred"],
        total=len(entries),
    )]

    for family, label in FAMILY_LABEL.items():
        members = [entry for entry in entries if entry.get("family") == family]
        if not members:
            continue
        out.append("## %s\n" % label)
        out.append("| Skill | Status | Priority | What it does |")
        out.append("| --- | --- | --- | --- |")
        for entry in sorted(members, key=lambda item: (STATUS_ORDER.index(item.get("status", "planned")), item["id"])):
            status = STATUS_LABEL.get(entry.get("status"), entry.get("status"))
            summary = entry.get("summary", "").strip().replace("|", "/")
            label = "`%s`" % entry["id"]
            if entry.get("status") == "flagship" and entry.get("path"):
                label = "[`%s`](../%s/SKILL.md)" % (entry["id"], entry["path"])
            out.append("| %s | %s | %s | %s |" % (
                label, status, entry.get("priority", "-"), summary
            ))
        out.append("")

    out.append("## Notes\n")
    out.append("- `flagship` skills exist on disk, pass `tools/validate_skills.py`, and ship at least")
    out.append("  three evaluation cases.")
    out.append("- `planned` and `deferred` skills intentionally have **no directory**; the catalog is the")
    out.append("  roadmap, not a promise.")
    out.append("- Maturity (`draft` → `stable`) is tracked separately from catalog status and lives in each")
    out.append("  `SKILL.md` frontmatter under `metadata.status`.")
    out.append("")
    return "\n".join(out)


def render_roadmap(entries):
    out = []
    out.append("<!-- Generated by tools/render_catalog.py from catalog/skills.yaml. Do not edit by hand. -->\n")
    out.append("# Roadmap\n")
    out.append("Priority reflects expected value divided by build-and-validation cost, not enthusiasm.")
    out.append("A skill moves to `flagship` only when it has a workflow, at least two references, three")
    out.append("evaluation cases (including a false-positive case), and passing validators.\n")
    out.append("## Shipped in 0.1.0\n")
    for entry in entries:
        if entry.get("status") == "flagship":
            out.append("- `%s` — %s" % (entry["id"], entry.get("summary", "").strip()))
    out.append("")
    for priority, title in (("P1", "Next"), ("P2", "Later"), ("P3", "Backlog")):
        rows = [entry for entry in entries if entry.get("priority") == priority and entry.get("status") in ("planned", "prototype")]
        if not rows:
            continue
        out.append("## %s" % title)
        out.append("")
        for entry in rows:
            out.append("- **`%s`** (%s) — %s" % (entry["id"], entry.get("family"), entry.get("summary", "").strip()))
        out.append("")
    deferred = [entry for entry in entries if entry.get("status") == "deferred"]
    if deferred:
        out.append("## Deferred, with reasons\n")
        for entry in deferred:
            out.append("- **`%s`** — %s" % (entry["id"], entry.get("summary", "").strip()))
        out.append("")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(description="Render catalog markdown views.")
    parser.add_argument("--root", default=lintlib.REPO_ROOT)
    parser.add_argument("--check", action="store_true", help="fail if the generated files are stale")
    args = parser.parse_args(argv)

    root = args.root
    data = yamlmini.load_file(os.path.join(root, "catalog", "skills.yaml"))
    entries = data["skills"]
    outputs = {
        os.path.join(root, "catalog", "SKILL_CATALOG.md"): render_catalog(entries),
        os.path.join(root, "catalog", "ROADMAP.md"): render_roadmap(entries),
    }

    stale = []
    for path, content in outputs.items():
        if args.check:
            current = lintlib.read_text(path) if os.path.isfile(path) else ""
            if current != content:
                stale.append(os.path.relpath(path, root))
        else:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(content)
            print("wrote %s" % os.path.relpath(path, root))

    if stale:
        sys.stderr.write("stale generated files: %s\nrun: python3 tools/render_catalog.py\n" % ", ".join(stale))
        return 1
    if args.check:
        print("catalog views are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
